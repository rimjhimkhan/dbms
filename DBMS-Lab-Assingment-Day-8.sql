-- Q9. Display student name, age and birth month
--     of all distinct students using UNION.

SELECT NAME,
       TRUNC(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) AS AGE,
       TRIM(TO_CHAR(BIRTHDAY, 'MONTH')) AS BIRTH_MONTH
FROM SPORTS_STUD

UNION

SELECT NAME,
       TRUNC(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) AS AGE,
       TRIM(TO_CHAR(BIRTHDAY, 'MONTH')) AS BIRTH_MONTH
FROM CULTURAL_STUD;


-- Q10. Display the last day of the birth month

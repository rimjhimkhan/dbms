-- Q2. Display FIRST_NAME in LOWER CASE
--     for departments 20, 50 or 80.

SELECT LOWER(FIRST_NAME) AS FIRST_NAME
FROM EMPLOYEE_DETAILS
WHERE DEPARTMENT_ID IN (20, 50, 80);


-- Q3. Display LAST_NAME in UPPER CASE
--     for departments 10, 110 or 60.

SELECT UPPER(LAST_NAME) AS LAST_NAME
FROM EMPLOYEE_DETAILS
WHERE DEPARTMENT_ID IN (10, 110, 60);


-- Q4. Display all JOB_ID in INITCAP format.

SELECT INITCAP(JOB_ID) AS JOB_ID
FROM EMPLOYEE_DETAILS;


-- Q5. Display employee full name using CONCAT function.

SELECT CONCAT(CONCAT(FIRST_NAME, ' '), LAST_NAME) AS EMPLOYEE_NAME
FROM EMPLOYEE_DETAILS;


-- Q6. Find the length of LAST_NAME
--     of employees getting commission.

SELECT LAST_NAME,
       LENGTH(LAST_NAME) AS NAME_LENGTH
FROM EMPLOYEE_DETAILS
WHERE COMMISSION_PCT IS NOT NULL;


-- Q7. Find the numeric position of letter 'a'
--     in FIRST_NAME of all employees.

SELECT FIRST_NAME,
       INSTR(LOWER(FIRST_NAME), 'a') AS POSITION_OF_A
FROM EMPLOYEE_DETAILS;


-- Q8. Display full name, last name length and
--     position of letter 'a' in LAST_NAME
--     for employees having CLERK in JOB_ID.

SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME,
       LENGTH(LAST_NAME) AS LAST_NAME_LENGTH,
       INSTR(LOWER(LAST_NAME), 'a') AS POSITION_OF_A
FROM EMPLOYEE_DETAILS
WHERE JOB_ID LIKE '%CLERK%';


-- Q9. Display SALARY in 10 characters
--     padded with '$' on the left side.

SELECT SALARY,
       LPAD(TO_CHAR(SALARY, 'FM99999990'), 10, '$') AS PADDED_SALARY
FROM EMPLOYEE_DETAILS;


-- Q10. Trim 'e' from FIRST_NAME
--      of employees having 'e' in their name.

SELECT FIRST_NAME,
       TRIM('e' FROM LOWER(FIRST_NAME)) AS "Trimmed"
FROM EMPLOYEE_DETAILS
WHERE LOWER(FIRST_NAME) LIKE '%e%';


-- Q11. Display DEPARTMENT_ID, SALARY and HIRE_DATE
--      of employees whose FIRST_NAME has exactly 6 characters.

SELECT DEPARTMENT_ID,
       SALARY,
       HIRE_DATE,
       LENGTH(FIRST_NAME) AS NAME_LENGTH
FROM EMPLOYEE_DETAILS
WHERE LENGTH(FIRST_NAME) = 6;


-- Q12. Display JOB_ID and position of 'e'
--      for employees whose FIRST_NAME contains 'e'.

SELECT JOB_ID,
       FIRST_NAME,
       INSTR(LOWER(FIRST_NAME), 'e') AS POSITION_OF_E
FROM EMPLOYEE_DETAILS
WHERE LOWER(FIRST_NAME) LIKE '%e%';


-- Q13. Display LAST_NAME of employees whose JOB_ID
--      contains REP starting at the fourth position.

SELECT LAST_NAME
FROM EMPLOYEE_DETAILS
WHERE INSTR(JOB_ID, 'REP', 4) > 0;


-- Q14. Calculate remainder of SALARY divided by 3000
--      for Sales Representatives.

SELECT FIRST_NAME,
       SALARY,
       MOD(SALARY, 3000) AS REMAINDER
FROM EMPLOYEE_DETAILS
WHERE JOB_ID = 'SA_REP';


-- Q15. Display SALARY in the format $7,000.00.

SELECT TO_CHAR(SALARY, 'FM$9,999,990.00') AS FORMATTED_SALARY
FROM EMPLOYEE_DETAILS;


-- Q16. Display SALARY in the format $7000
--      for departments 60, 90 or 110.

SELECT FIRST_NAME,
       TO_CHAR(SALARY, 'FM$9999990') AS FORMATTED_SALARY
FROM EMPLOYEE_DETAILS
WHERE DEPARTMENT_ID IN (60, 90, 110);


-- Q17. Display LAST_NAME and COMMISSION.
--      If commission is NULL, display No Commission.

SELECT LAST_NAME,
       NVL(TO_CHAR(COMMISSION_PCT), 'No Commission') AS COMM
FROM EMPLOYEE_DETAILS;


-- Q18. Find number of days elapsed between today
--      and HIRE_DATE. Round off the days.

SELECT FIRST_NAME,
       ROUND(SYSDATE - HIRE_DATE) AS DAYS_WORKED
FROM EMPLOYEE_DETAILS;


-- Q19. Find number of weeks elapsed between today
--      and HIRE_DATE.

SELECT FIRST_NAME,
       ROUND((SYSDATE - HIRE_DATE) / 7, 2) AS WEEKS_WORKED
FROM EMPLOYEE_DETAILS;


-- Q20. Find number of years elapsed between today
--      and HIRE_DATE. Round off the years.

SELECT FIRST_NAME,
       ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE) / 12) AS YEARS_WORKED
FROM EMPLOYEE_DETAILS;


-- Q21. Display employee name and months worked.

SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME,
       ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)) AS MONTHS_WORKED
FROM EMPLOYEE_DETAILS;


-- Q22. Display employee name and last day
--      of the month in which they were hired.

SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME,
       LAST_DAY(HIRE_DATE) AS LAST_DAY_OF_MONTH
FROM EMPLOYEE_DETAILS;


-- Q23. Display employee name and hiring year in words.

SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME,
       TRIM(TO_CHAR(HIRE_DATE, 'YEAR')) AS HIRE_YEAR
FROM EMPLOYEE_DETAILS;


-- Q24. Display date 5 months later than today's date.

SELECT ADD_MONTHS(SYSDATE, 5) AS "FUTURE DATE"
FROM DUAL;


-- Q25. Display employee name, day and date of joining.

SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME,
       TO_CHAR(HIRE_DATE, 'DAY') AS JOINING_DAY,
       TO_CHAR(HIRE_DATE, 'DD-MON-YYYY') AS JOINING_DATE
FROM EMPLOYEE_DETAILS;


-- Q26. Display annual salary and rounded annual salary.
--      Annual Salary = (SALARY * 12) + COMMISSION_PCT

SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME,
       (SALARY * 12) + NVL(COMMISSION_PCT, 0) AS ANNUAL_SALARY,
       ROUND((SALARY * 12) + NVL(COMMISSION_PCT, 0), 2)
       AS ROUNDED_ANNUAL_SALARY
FROM EMPLOYEE_DETAILS;